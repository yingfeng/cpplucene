struct Range {
    char32_t first;
    char32_t last;
};

constexpr bool in_ranges(char32_t cp, std::span<const Range> ranges) noexcept {
    size_t low = 0;
    size_t high = ranges.size();
    while (low < high) {
        const size_t mid = low + (high - low) / 2;
        if (cp < ranges[mid].first) {
            high = mid;
        } else if (cp > ranges[mid].last) {
            low = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

